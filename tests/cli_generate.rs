/// Guardrail — pins the Phase 3 anchor-orb re-tiering (D-09/D-10).
///
/// Asserts that the price-driven generator output reflects the three anchor orb moves:
///   - Divine Orb: S → A  (220c = A lower bound)
///   - Exalted Orb: C → D  (4.5c ≥ D lower bound of 2c)
///   - Chaos Orb: C → E   (1c ≥ E lower bound of 0.5c)
///
/// Any future drift in the generator or prices.json that causes these orbs to land in
/// a different tier will be caught here before it reaches the committed universal.filter.
///
/// Satisfies T-03-09 (tampering guard) and documents D-10 re-baseline intent.
#[test]
fn currency_retiering_present() {
    let output = generate_on_seed();

    // Helper: find the BaseType line following a Show block with the given comment slug.
    let find_basetype = |slug: &str| -> Option<String> {
        let mut lines = output.lines();
        while let Some(line) = lines.next() {
            if line.starts_with("Show #") && line.contains(slug) {
                // The next non-empty, non-comment line starting with "  Class" is skipped;
                // the line after that starting with "  BaseType" is what we want.
                for next_line in lines.by_ref() {
                    if next_line.trim_start().starts_with("BaseType") {
                        return Some(next_line.to_string());
                    }
                }
            }
        }
        None
    };

    // Currency A block must contain "Divine Orb" (moved from S)
    let a_line = find_basetype("Currency A").expect("Currency A block not found");
    assert!(
        a_line.contains("\"Divine Orb\""),
        "Currency A BaseType should contain \"Divine Orb\" (re-tiered from S); got: {a_line}"
    );

    // Currency S block must NOT contain "Divine Orb"
    let s_line = find_basetype("Currency S").expect("Currency S block not found");
    assert!(
        !s_line.contains("\"Divine Orb\""),
        "Currency S BaseType should NOT contain \"Divine Orb\" (re-tiered to A); got: {s_line}"
    );

    // Currency D block must contain "Exalted Orb" (moved from C)
    let d_line = find_basetype("Currency D").expect("Currency D block not found");
    assert!(
        d_line.contains("\"Exalted Orb\""),
        "Currency D BaseType should contain \"Exalted Orb\" (re-tiered from C); got: {d_line}"
    );

    // Currency E block must contain "Chaos Orb" (moved from C)
    let e_line = find_basetype("Currency E").expect("Currency E block not found");
    assert!(
        e_line.contains("\"Chaos Orb\""),
        "Currency E BaseType should contain \"Chaos Orb\" (re-tiered from C); got: {e_line}"
    );

    // Currency C block must NOT contain "Chaos Orb" or "Exalted Orb"
    let c_line = find_basetype("Currency C").expect("Currency C block not found");
    assert!(
        !c_line.contains("\"Chaos Orb\""),
        "Currency C BaseType should NOT contain \"Chaos Orb\" (re-tiered to E); got: {c_line}"
    );
    assert!(
        !c_line.contains("\"Exalted Orb\""),
        "Currency C BaseType should NOT contain \"Exalted Orb\" (re-tiered to D); got: {c_line}"
    );
}

// NOTE (Phase 7 / Plan 07-02): The `parity_policy_blocks_match_oracle` test that compared
// `--early-game` output to `tests/fixtures/parity-baseline-earlygame.filter` (the Phase 6
// pre-edit baseline) has been removed. The 7 CAP edits (Plan 07-01) deliberately changed the
// policy output, making it permanently mismatched against that old oracle. The pre-edit
// baseline fixture is kept as a historical artifact only. The Phase 7 parity gate is now
// `parity_ingame` below, which compares against the updated in-game oracle.

/// Phase 7 parity gate — `generate --early-game` POLICY blocks must be semantically equivalent
/// (order- and comment-insensitive) to the frozen in-game oracle `parity-ingame.filter`.
///
/// Only the policy section (before `# --- Currency ---`) is compared. The pricer-driven
/// currency/unique sections are excluded — pricer differences (Vaal Infuser, Tablets absent
/// in `foo.filter`) are DATA drift from the new game version, not policy edits.
///
/// Satisfies CAP-01..06 parity gate (MIG-02 / T-07-04).
#[test]
fn parity_ingame() {
    let generated = generate_early_game();
    let oracle = normalize(
        &fs::read_to_string(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/tests/fixtures/parity-ingame.filter"
        ))
        .unwrap(),
    );
    let gen_set = policy_blocks(&generated);
    let oracle_set = policy_blocks(&oracle);

    // Surface differences explicitly for author review (anything beyond pure reordering).
    let only_in_oracle: Vec<_> = oracle_set.difference(&gen_set).collect();
    let only_in_generated: Vec<_> = gen_set.difference(&oracle_set).collect();
    assert!(
        only_in_oracle.is_empty() && only_in_generated.is_empty(),
        "policy-block parity mismatch.\n  Only in oracle: {:#?}\n  Only in generated: {:#?}",
        only_in_oracle,
        only_in_generated
    );
}

/// Rule-driven cap test — proves that changing a CAP rule value in config.json changes
/// the emitted filter output, i.e. the generator is declarative, not hardcoded.
///
/// Mutates CAP-01/CAP-02's `areaLevel.max` from 75 to 60 (sentinel) in config.json,
/// regenerates with `--early-game`, and asserts:
///   - `AreaLevel <= 60` is present (the sentinel value made it through)
///   - `AreaLevel <= 75` is absent (the original value is gone)
///
/// Satisfies CAP-01 rule-driven requirement.
#[test]
fn cap_is_rule_driven() {
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let dir = std::env::temp_dir().join(format!(
        "ferrisfilter_cap_test_{:x}",
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos()
    ));
    std::fs::create_dir_all(&dir).expect("create temp cap test dir");

    // Read config.json and mutate the areaLevel.max=75 sentinel to 60.
    // CAP-01 (build weapons) and CAP-02 (build armour) both use max:75; replacing all is fine.
    let config_text = std::fs::read_to_string(manifest.join("config.json"))
        .expect("read config.json");
    let mutated_config = config_text.replace("\"max\": 75", "\"max\": 60");

    // Write the mutated config + other required fallback files into the temp dir.
    std::fs::write(dir.join("config.json"), mutated_config).expect("write mutated config.json");
    for f in ["currency.json", "prices-fallback.json", "tiers-fallback.json"] {
        std::fs::copy(manifest.join(f), dir.join(f)).unwrap_or_else(|e| panic!("copy {f}: {e}"));
    }

    let out_path = dir.join("out.filter");
    Command::cargo_bin("ferrisfilter")
        .unwrap()
        .current_dir(&dir)
        .args(["generate", "--early-game", "--output", out_path.to_str().unwrap()])
        .assert()
        .success();

    let output = normalize(&std::fs::read_to_string(&out_path).expect("read cap test output"));

    assert!(
        output.contains("AreaLevel <= 60"),
        "cap_is_rule_driven: expected 'AreaLevel <= 60' in output (sentinel value), but not found"
    );
    assert!(
        !output.contains("AreaLevel <= 75"),
        "cap_is_rule_driven: expected 'AreaLevel <= 75' to be absent after mutation, but it is still present"
    );
}

/// Confirms the pricer-driven section is present and uses the correct format.
///
/// Asserts that the seed output contains the `# --- Currency ---` marker and the
/// Currency tier blocks, and that pricer blocks use `Class == "Stackable Currency"`
/// (with `==`) distinct from policy blocks' bare `Class`. This guards that the rewrite
/// did not accidentally route currency through `emit_rules`.
///
/// Satisfies MIG-04.
#[test]
fn pricer_section_present_and_unchanged() {
    let output = generate_on_seed();

    // The currency section marker must be present
    assert!(
        output.contains("# --- Currency ---"),
        "pricer section marker '# --- Currency ---' not found in output"
    );

    // Currency tier blocks S through F must exist
    for tier in &["Currency S", "Currency A", "Currency B", "Currency C", "Currency D", "Currency E", "Currency F"] {
        assert!(
            output.contains(&format!("Show # {}", tier)),
            "Currency tier block '{}' not found in output",
            tier
        );
    }

    // Pricer blocks use Class == "Stackable Currency" (with ==), not bare Class
    assert!(
        output.contains("Class == \"Stackable Currency\""),
        "pricer currency blocks must use 'Class == \"Stackable Currency\"' (with ==); not found"
    );

    // Pricer blocks use BaseType == (with ==)
    assert!(
        output.contains("BaseType =="),
        "pricer currency blocks must use 'BaseType ==' (with ==); not found"
    );

    // Policy blocks must NOT use Class == for gear/flask blocks (bare Class, no ==)
    // Verify the recycle block uses bare Class (no ==) — confirming emit_rules is used for policy
    let policy_section = {
        let cut = "# --- Currency ---";
        if let Some(pos) = output.find(cut) {
            &output[..pos]
        } else {
            &output[..]
        }
    };
    assert!(
        !policy_section.contains("Class == "),
        "policy section must not contain 'Class == ' (bare Class is correct for policy blocks)"
    );
}
