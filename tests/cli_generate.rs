use assert_cmd::Command;
use predicates::str::contains;
use std::fs;

/// Normalize CRLF line endings to LF.
///
/// Required for CRLF-safe test comparisons on Windows: the generator emits LF-only
/// (`writeln!` produces `\n`), but the working-tree `universal.filter` is checked out
/// as CRLF on Windows (`.gitattributes` has `*.filter text` + `core.autocrlf=true`).
/// Always normalize both sides before comparing or snapshotting.
fn normalize(s: &str) -> String {
    s.replace("\r\n", "\n")
}

/// Run `generate` hermetically against the committed seed fixture.
///
/// Copies the committed inputs (config/currency/tiers) plus `tests/fixtures/seed-prices.json`
/// (as `prices.json`) into a fresh temp dir, runs the binary there, and returns the
/// CRLF-normalized output. This decouples the content tests from the repo-root `prices.json`,
/// which is generated by `sync` and git-ignored — so the tests are stable regardless of
/// whatever live data happens to be in the working tree.
fn generate_on_seed() -> String {
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let dir = std::env::temp_dir().join(format!(
        "ferrisfilter_gen_seed_{:x}",
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos()
    ));
    fs::create_dir_all(&dir).expect("create temp gen dir");
    for f in ["config.json", "currency.json", "tiers.json"] {
        fs::copy(manifest.join(f), dir.join(f)).unwrap_or_else(|e| panic!("copy {f}: {e}"));
    }
    fs::copy(
        manifest.join("tests/fixtures/seed-prices.json"),
        dir.join("prices.json"),
    )
    .expect("copy seed-prices.json fixture");

    let out_path = dir.join("out.filter");
    Command::cargo_bin("ferrisfilter")
        .unwrap()
        .current_dir(&dir)
        .args(["generate", "--output", out_path.to_str().unwrap()])
        .assert()
        .success();

    normalize(&fs::read_to_string(&out_path).expect("read generated filter"))
}

/// `ferrisfilter --help` lists both subcommands.
#[test]
fn help_lists_subcommands() {
    Command::cargo_bin("ferrisfilter")
        .unwrap()
        .arg("--help")
        .assert()
        .success()
        .stdout(contains("generate"))
        .stdout(contains("sync"));
}

