/// `ferrisfilter generate` run from the repo root (where config.json and tiers.json
/// exist) must exit successfully.
///
/// Satisfies ROADMAP success criterion — generate + valid inputs → exit 0.
///
/// Uses `--output <tmpfile>` to avoid clobbering the committed `universal.filter`
/// during test runs (which would make artifact_guard compare the test's output
/// against itself, defeating its purpose).
#[test]
fn generate_in_repo_root_succeeds() {
    // The test binary's cwd is the Cargo manifest directory, which is the repo root.
    // config.json is created by plan 01-02; tiers.json is created by plan 01-03.
    // In the merged state both files exist at the repo root, so this test passes.
    //
    // In the plan 01-03 worktree, config.json does not exist yet (plan 01-02 owns it),
    // so we skip this test if it is absent.
    let config_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("config.json");
    if !config_path.exists() {
        eprintln!("SKIP: config.json not present in this worktree (plan 01-02 owns it)");
        return;
    }

    let out_path = std::env::temp_dir().join("ferrisfilter_repo_root_test.filter");

    Command::cargo_bin("ferrisfilter")
        .unwrap()
        .current_dir(env!("CARGO_MANIFEST_DIR"))
        .args(["generate", "--output", out_path.to_str().unwrap()])
        .assert()
        .success();
}

/// Snapshot test — locks the generator output against future regression (D-05).
///
/// Runs `ferrisfilter generate --output <tmp>` from the repo root (where config.json,
/// currency.json, and tiers.json live), reads the produced file, normalizes CRLF→LF,
/// and asserts it matches the committed snapshot oracle.
///
/// To update the snapshot after a deliberate generator change:
///   `INSTA_UPDATE=always cargo test --test cli_generate` then review the diff and commit
///   the updated `tests/snapshots/cli_generate__generate_snapshot.snap`.
#[test]
fn generate_snapshot() {
    insta::assert_snapshot!("generate_snapshot", generate_on_seed());
}

/// Artifact-guard test — asserts the generator output matches the committed
/// `tests/fixtures/seed-universal.filter` oracle, so the generator can't silently drift.
///
/// The repo-root `universal.filter` is no longer committed (it's generated by `generate`
/// and git-ignored); the seed fixture is the stable oracle. Both sides are CRLF-normalized.
///
/// If this test fails after a deliberate generator change, regenerate the fixture:
///   copy a fresh `generate` (on the seed inputs) over `tests/fixtures/seed-universal.filter`.
#[test]
fn artifact_guard() {
    let generated = generate_on_seed();
    let oracle = normalize(
        &fs::read_to_string(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/tests/fixtures/seed-universal.filter"
        ))
        .expect("read seed-universal.filter fixture"),
    );

    assert_eq!(
        generated, oracle,
        "generator output does not match tests/fixtures/seed-universal.filter — \
         regenerate the fixture from `generate` on the seed inputs"
    );
}

/// Determinism test — two consecutive `generate` runs with identical inputs must produce
/// byte-identical output (GEN-01 / D-07).
///
/// Both outputs are CRLF-normalized before comparison.
#[test]
fn generate_is_deterministic() {
    assert_eq!(
        generate_on_seed(),
        generate_on_seed(),
        "generate() is not deterministic across two runs"
    );
}

/// Guardrail — pins the Phase 3 anchor-orb re-tiering (D-09/D-10).
///
/// Asserts that the price-driven generator output reflects the three anchor orb moves:
///   - Divine Orb: S → A  (220c = A lower bound)
///   - Exalted Orb: C → D  (4.5c ≥ D lower bound of 2c)
///   - Chaos Orb: C → E   (1c ≥ E lower bound of 0.5c)
///
/// Any future drift in the generator or prices.json that causes these orbs to land in
/// a different tier will be caught here before it reaches the committed universal.filter.
///
/// Satisfies T-03-09 (tampering guard) and documents D-10 re-baseline intent.
#[test]
fn currency_retiering_present() {
    let output = generate_on_seed();

    // Helper: find the BaseType line following a Show block with the given comment slug.
    let find_basetype = |slug: &str| -> Option<String> {
        let mut lines = output.lines();
        while let Some(line) = lines.next() {
            if line.starts_with("Show #") && line.contains(slug) {
                // The next non-empty, non-comment line starting with "  Class" is skipped;
                // the line after that starting with "  BaseType" is what we want.
                for next_line in lines.by_ref() {
                    if next_line.trim_start().starts_with("BaseType") {
                        return Some(next_line.to_string());
                    }
                }
            }
        }
        None
    };

    // Currency A block must contain "Divine Orb" (moved from S)
    let a_line = find_basetype("Currency A").expect("Currency A block not found");
    assert!(
        a_line.contains("\"Divine Orb\""),
        "Currency A BaseType should contain \"Divine Orb\" (re-tiered from S); got: {a_line}"
    );

    // Currency S block must NOT contain "Divine Orb"
    let s_line = find_basetype("Currency S").expect("Currency S block not found");
    assert!(
        !s_line.contains("\"Divine Orb\""),
        "Currency S BaseType should NOT contain \"Divine Orb\" (re-tiered to A); got: {s_line}"
    );

    // Currency D block must contain "Exalted Orb" (moved from C)
    let d_line = find_basetype("Currency D").expect("Currency D block not found");
    assert!(
        d_line.contains("\"Exalted Orb\""),
        "Currency D BaseType should contain \"Exalted Orb\" (re-tiered from C); got: {d_line}"
    );

    // Currency E block must contain "Chaos Orb" (moved from C)
    let e_line = find_basetype("Currency E").expect("Currency E block not found");
    assert!(
        e_line.contains("\"Chaos Orb\""),
        "Currency E BaseType should contain \"Chaos Orb\" (re-tiered from C); got: {e_line}"
    );

    // Currency C block must NOT contain "Chaos Orb" or "Exalted Orb"
    let c_line = find_basetype("Currency C").expect("Currency C block not found");
    assert!(
        !c_line.contains("\"Chaos Orb\""),
        "Currency C BaseType should NOT contain \"Chaos Orb\" (re-tiered to E); got: {c_line}"
    );
    assert!(
        !c_line.contains("\"Exalted Orb\""),
        "Currency C BaseType should NOT contain \"Exalted Orb\" (re-tiered to D); got: {c_line}"
    );
}
