    #[test]
    fn banner_lines_are_never_inside_a_block() {
        // No blank line between a block (live, commented-out, or with commented-out body lines)
        // and the banner below it.
        let shapes = [
            "Show # A\n  Rarity Rare\n",
            "# Show # A\n# \tRarity Rare\n",
            "Show # A\n  Rarity Rare\n#\tSetFontSize 40\n",
        ];
        for top in shapes {
            let s = format!(
                "{top}{RULE_LINE}\n# ff:section Mid\n{RULE_LINE}\nShow # B\n  Class \"Rings\"\n"
            );
            let d = doc(&s);
            let at = top.lines().count();
            assert_eq!(banners(&d).len(), 1, "{top}");
            assert_eq!(banners(&d)[0].start, at, "{top}");
            for b in d.blocks() {
                let o = b.owned();
                for m in at..at + 3 {
                    assert!(
                        !b.span().contains(&m),
                        "line {m} inside a block for {top:?}"
                    );
                    assert!(!o.contains(&m));
                }
            }
            let last = d.blocks().last().unwrap();
            assert_eq!(last.span().start, at + 3, "{top}");
            assert_eq!(d.serialize(), s);
        }
    }

