//! The economy section: a marker-fenced region at the end of a filter that FerrisFilter owns.
//!
//! Everything here is a pure text operation over the lossless parser (no I/O, no printing):
//! locate and validate the markers ([`find`]), replace only the lines between them ([`refresh`]),
//! [`add`] and [`remove`] the section as explicit, separate operations, and convert the v0.4
//! `dynamic.filter` layout in memory ([`migrate_v04`]).
//!
//! Marker lines are `#ff:economy-begin ...` / `#ff:economy-end ...`. Both are found by key through
//! `Line::ff_marker`, never by raw substring search, so a disabled-style `# #ff:economy-begin`
//! or a marker in a header comment is not a marker.

use miette::Diagnostic;
use thiserror::Error;

use super::{Document, Eol};

pub const BEGIN_KEY: &str = "economy-begin";
pub const END_KEY: &str = "economy-end";
pub const BEGIN_LINE: &str = "#ff:economy-begin Generated by FerrisFilter from prices.json, tiers.json and styles.json. Do not edit; Apply regenerates everything up to economy-end.";
pub const END_LINE: &str = "#ff:economy-end End of the FerrisFilter economy section.";

const V04_TITLE: &str = "# dynamic.filter";
const V04_SOURCE_PREFIX: &str = "# GENERATED FROM dynamic.json";
const V04_BANNER: &str = "#============================================================";
const V04_ECONOMY_PREFIX: &str = "# alwaysShow.currency";

/// 0-based line indices of the two marker lines.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SectionSpan {
    pub begin: usize,
    pub end: usize,
}

#[derive(Debug, Clone, PartialEq, Eq, Error, Diagnostic)]
pub enum SectionError {
    #[error("economy section is damaged: `#ff:economy-end` on line {line} has no `#ff:economy-begin` above it; fix or delete the marker by hand, nothing was written")]
    EndWithoutBegin { line: usize },
    #[error("economy section is damaged: `#ff:economy-begin` on line {line} has no `#ff:economy-end` below it; fix or delete the marker by hand, nothing was written")]
    BeginWithoutEnd { line: usize },
    #[error("economy section is damaged: `#ff:economy-end` on line {end} comes before `#ff:economy-begin` on line {begin}; fix the markers by hand, nothing was written")]
    EndBeforeBegin { begin: usize, end: usize },
    #[error("economy section is damaged: `#ff:economy-begin` appears more than once (lines {lines:?}); delete the extra marker by hand, nothing was written")]
    DuplicateBegin { lines: Vec<usize> },
    #[error("economy section is damaged: `#ff:economy-end` appears more than once (lines {lines:?}); delete the extra marker by hand, nothing was written")]
    DuplicateEnd { lines: Vec<usize> },
    #[error("economy section is damaged: an economy marker on line {line} sits inside a rule block; move it out by hand, nothing was written")]
    MarkerInsideBlock { line: usize },
    #[error("this filter has no economy section")]
    NoSection,
    #[error("this filter already has an economy section (begin marker on line {line})")]
    AlreadyPresent { line: usize },
    #[error("the generated body contains an economy marker on its line {line}; refusing to splice it")]
    BodyContainsMarker { line: usize },
    #[error("could not parse the filter: {0}")]
    Parse(String),
    #[error("could not convert the v0.4 filter: {0}")]
    Migration(String),
}

fn parse_doc(text: &str) -> Result<Document, SectionError> {
    super::parse(text.as_bytes()).map_err(|e| SectionError::Parse(e.to_string()))
}

fn marker_key(text: &str) -> Option<&str> {
    super::meta::parse_ff_line(text).map(|(k, _)| k)
}

/// Locate and validate the section markers.
pub fn find(doc: &Document) -> Result<Option<SectionSpan>, SectionError> {
    let mut begins = Vec::new();
    let mut ends = Vec::new();
    for (i, l) in doc.lines().iter().enumerate() {
        match l.ff_marker().map(|(k, _)| k) {
            Some(BEGIN_KEY) => begins.push(i),
            Some(END_KEY) => ends.push(i),
            _ => {}
        }
    }
    if begins.len() > 1 {
        return Err(SectionError::DuplicateBegin {
            lines: begins.iter().map(|i| i + 1).collect(),
        });
    }
    if ends.len() > 1 {
        return Err(SectionError::DuplicateEnd {
            lines: ends.iter().map(|i| i + 1).collect(),
        });
    }
    let span = match (begins.first(), ends.first()) {
        (None, None) => return Ok(None),
        (None, Some(&e)) => return Err(SectionError::EndWithoutBegin { line: e + 1 }),
        (Some(&b), None) => return Err(SectionError::BeginWithoutEnd { line: b + 1 }),
        (Some(&b), Some(&e)) if e < b => {
            return Err(SectionError::EndBeforeBegin {
                begin: b + 1,
                end: e + 1,
            })
        }
        (Some(&b), Some(&e)) => SectionSpan { begin: b, end: e },
    };
    for blk in doc.blocks() {
        let r = blk.owned();
        for m in [span.begin, span.end] {
            if r.contains(&m) {
                return Err(SectionError::MarkerInsideBlock { line: m + 1 });
            }
        }
    }
    Ok(Some(span))
}

pub fn has_section(text: &str) -> Result<bool, SectionError> {
    Ok(find(&parse_doc(text)?)?.is_some())
}

fn body_lines(body: &str) -> Result<Vec<&str>, SectionError> {
    let mut v: Vec<&str> = body.split('\n').collect();
    if v.last() == Some(&"") {
        v.pop();
    }
    let v: Vec<&str> = v
        .into_iter()
        .map(|l| l.strip_suffix('\r').unwrap_or(l))
        .collect();
    for (i, l) in v.iter().enumerate() {
        if matches!(marker_key(l), Some(BEGIN_KEY) | Some(END_KEY)) {
            return Err(SectionError::BodyContainsMarker { line: i + 1 });
        }
    }
    Ok(v)
}

fn push_line(out: &mut String, text: &str, eol: Eol) {
    out.push_str(text);
    out.push_str(eol.as_str());
}

fn require_one_span(out: String) -> Result<String, SectionError> {
    match find(&parse_doc(&out)?)? {
        Some(_) => Ok(out),
        None => Err(SectionError::NoSection),
    }
}

/// Replace only the lines strictly between the markers with `["", body..., ""]`.
pub fn refresh(text: &str, body: &str) -> Result<String, SectionError> {
    let body = body_lines(body)?;
    let doc = parse_doc(text)?;
    let span = find(&doc)?.ok_or(SectionError::NoSection)?;
    let lines = doc.lines();
    let eol = lines[span.begin].eol();
    let mut out = String::new();
    if doc.has_bom() {
        out.push('\u{feff}');
    }
    for l in &lines[..=span.begin] {
        push_line(&mut out, l.text(), l.eol());
    }
    push_line(&mut out, "", eol);
    for b in &body {
        push_line(&mut out, b, eol);
    }
    push_line(&mut out, "", eol);
    for l in &lines[span.end..] {
        push_line(&mut out, l.text(), l.eol());
    }
    require_one_span(out)
}

/// Append a new section at the end of the file. Errors if one already exists.
pub fn add(text: &str, body: &str) -> Result<String, SectionError> {
    let body = body_lines(body)?;
    let doc = parse_doc(text)?;
    if let Some(span) = find(&doc)? {
        return Err(SectionError::AlreadyPresent {
            line: span.begin + 1,
        });
    }
    let lines = doc.lines();
    let eol = lines
        .iter()
        .rev()
        .map(|l| l.eol())
        .find(|e| *e != Eol::None)
        .unwrap_or(Eol::Lf);
    let mut out = String::new();
    if doc.has_bom() {
        out.push('\u{feff}');
    }
    for l in lines {
        push_line(&mut out, l.text(), l.eol());
    }
    if let Some(last) = lines.last() {
        if last.eol() == Eol::None {
            out.push_str(eol.as_str());
        }
        push_line(&mut out, "", eol);
    }
    push_line(&mut out, BEGIN_LINE, eol);
    push_line(&mut out, "", eol);
    for b in &body {
        push_line(&mut out, b, eol);
    }
    push_line(&mut out, "", eol);
    push_line(&mut out, END_LINE, eol);
    require_one_span(out)
}

/// Delete the section (markers inclusive) and the one blank line directly above it, if any.
pub fn remove(text: &str) -> Result<String, SectionError> {
    let doc = parse_doc(text)?;
    let span = find(&doc)?.ok_or(SectionError::NoSection)?;
    let lines = doc.lines();
    let mut start = span.begin;
    if start > 0 && lines[start - 1].text().trim().is_empty() {
        start -= 1;
    }
    let mut out = String::new();
    if doc.has_bom() {
        out.push('\u{feff}');
    }
    for (i, l) in lines.iter().enumerate() {
        if i >= start && i <= span.end {
            continue;
        }
        push_line(&mut out, l.text(), l.eol());
    }
    Ok(out)
}

// ---- v0.4 migration -------------------------------------------------------------------------

fn v04_banner_index(doc: &Document) -> Option<usize> {
    let lines = doc.lines();
    let mut hits = (0..lines.len().saturating_sub(1)).filter(|&i| {
        lines[i].text() == V04_BANNER && lines[i + 1].text().starts_with(V04_ECONOMY_PREFIX)
    });
    let first = hits.next()?;
    if hits.next().is_some() {
        return None;
    }
    Some(first)
}

/// True only for the author's v0.4 `dynamic.filter` layout: title, source line, no markers, and
/// exactly one economy banner. All three are required (no half-migration).
pub fn is_v04(text: &str) -> bool {
    let Ok(doc) = parse_doc(text) else {
        return false;
    };
    if !matches!(find(&doc), Ok(None)) {
        return false;
    }
    let lines = doc.lines();
    lines.len() > 1
        && lines[0].text() == V04_TITLE
        && lines[1].text().starts_with(V04_SOURCE_PREFIX)
        && v04_banner_index(&doc).is_some()
}

fn is_derived_label(s: &str) -> bool {
    s.strip_prefix("rule ")
        .is_some_and(|d| !d.is_empty() && d.bytes().all(|b| b.is_ascii_digit()))
}

/// Convert a v0.4 `dynamic.filter` to the marker layout, in memory only.
///
/// Wraps the economy (banner to EOF) in the markers and turns each hand-given header comment into
/// a `#ff:name` line; every other original line stays byte-identical, including the `# GENERATED
/// FROM dynamic.json` header (D-16). The caller keeps the original bytes as its guard baseline and
/// writes only on the next Apply (D-06, D-10).
pub fn migrate_v04(text: &str) -> Result<Option<String>, SectionError> {
    if !is_v04(text) {
        return Ok(None);
    }
    let mut doc = parse_doc(text)?;
    let banner = v04_banner_index(&doc).ok_or(SectionError::NoSection)?;
    let mut names = Vec::new();
    for b in doc.blocks() {
        if b.header_line() >= banner {
            continue;
        }
        let header = doc.lines()[b.header_line()].text();
        let Some((_, comment)) = header.split_once('#') else {
            continue;
        };
        let name = comment.trim();
        if name.is_empty() || is_derived_label(name) {
            continue;
        }
        names.push((b.id(), name.to_string()));
    }
    for (id, name) in names {
        doc.set_meta(id, "name", &name)
            .map_err(|e| SectionError::Migration(e.to_string()))?;
    }
    let doc = parse_doc(&doc.serialize())?;
    let banner = v04_banner_index(&doc).ok_or(SectionError::NoSection)?;
    let lines = doc.lines();
    let eol = lines[banner].eol();
    let mut out = String::new();
    if doc.has_bom() {
        out.push('\u{feff}');
    }
    for l in &lines[..banner] {
        push_line(&mut out, l.text(), l.eol());
    }
    push_line(&mut out, BEGIN_LINE, eol);
    push_line(&mut out, "", eol);
    let mut last_eol = eol;
    for l in &lines[banner..] {
        let e = if l.eol() == Eol::None { last_eol } else { l.eol() };
        last_eol = e;
        push_line(&mut out, l.text(), e);
    }
    push_line(&mut out, "", last_eol);
    push_line(&mut out, END_LINE, last_eol);
    Ok(Some(require_one_span(out)?))
}

